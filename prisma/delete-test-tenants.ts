import "dotenv/config";
import { readFileSync } from "node:fs";
import { Client } from "pg";
import { TENANT_OWNED_TABLES } from "@/lib/tenant-tables";

/**
 * One-off: removes the accumulated test tenants from PRODUCTION, exactly the two groups that were
 * reviewed and approved — nothing matched at execution time by pattern alone.
 *
 * Guards, because this is irreversible:
 *   - refuses unless DIRECT_URL is the production project
 *   - PROTECTED slugs abort the whole run if they ever appear in the delete set
 *   - resolves slugs -> ids and prints the count before touching anything
 *   - one transaction; any failure rolls the whole thing back
 */
const PROD_REF = "ntzwlkgqzkxworwuiqlh";

/** Group 1: generated by the e2e suite. */
const GENERATED = /^(isolation-test-|enum-probe-|e2e-|canary|perm-probe)/;

/** Group 2: named by hand during earlier testing. */
const NAMED = [
  "audit-test-tenant-b",
  "phase-c-test-diner-2",
  "phase-d-starter-test",
  "qa-final-pass",
  "feature-toggle-qa-test",
  "loophole-test-1-17875270071",
  "loophole-test-2-17875270122",
  "loophole-test-3-17875270153",
  "crash-audit-1877",
  "overnight-test-complete-tenant",
  "verify-free-1788664328759",
];

/** Never deletable by this script, whatever else matches. */
const PROTECTED = new Set([
  "karachi-karahi",
  "slice",
  "bigmac",
  "sigma",
  "blanco",
  "layers",
  "pizza",
  "grabb",
  "kebabish",
]);

(async () => {
  const url =
    readFileSync(".env.backup-predupe", "utf8").match(/^DIRECT_URL\s*=\s*["']?([^"'\r\n]+)/m)?.[1] ?? "";
  if (!url.includes(PROD_REF)) throw new Error("DIRECT_URL is not the production project. Refusing.");

  const c = new Client({ connectionString: url });
  await c.connect();

  const all = (await c.query<{ id: string; slug: string }>('SELECT id, slug FROM "Tenant"')).rows;
  const target = all.filter((t) => GENERATED.test(t.slug) || NAMED.includes(t.slug));

  const violation = target.filter((t) => PROTECTED.has(t.slug));
  if (violation.length) throw new Error(`ABORT — protected tenant in delete set: ${violation.map((v) => v.slug).join(", ")}`);

  const missing = NAMED.filter((s) => !all.some((t) => t.slug === s));
  if (missing.length) console.log(`note: ${missing.length} named tenant(s) already gone: ${missing.join(", ")}`);

  console.log(`Deleting ${target.length} tenants from production.`);
  console.log(`Protected and untouched: ${[...PROTECTED].join(", ")}\n`);

  const ids = target.map((t) => t.id);
  let total = 0;
  await c.query("BEGIN");
  try {
    for (const table of TENANT_OWNED_TABLES) {
      const r = await c.query(`DELETE FROM "${table}" WHERE "tenantId" = ANY($1::text[])`, [ids]);
      if (r.rowCount) total += r.rowCount;
    }
    const t = await c.query('DELETE FROM "Tenant" WHERE id = ANY($1::text[])', [ids]);
    await c.query("COMMIT");
    console.log(`Deleted ${t.rowCount} tenants and ${total} related rows.`);
  } catch (e) {
    await c.query("ROLLBACK");
    throw e;
  }

  const after = (await c.query<{ slug: string; status: string }>('SELECT slug, status FROM "Tenant" ORDER BY slug')).rows;
  console.log(`\nRemaining: ${after.length} tenants`);
  after.forEach((t) => console.log(`   ${t.slug.padEnd(34)} ${t.status}`));

  await c.end();
})().catch((e) => {
  console.error("FAILED:", e.message);
  process.exit(1);
});
